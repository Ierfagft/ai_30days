# ========== 1. 定义带异常捕获的除法函数 ==========
def divide(a, b):
    """
    安全除法函数：捕捉除零错误，避免程序崩溃。
    """
    try:
        result = a / b
        return result
    except ZeroDivisionError:
        # 捕获到除零错误时，返回一个友好的提示信息
        return "除数不能为0"

# ========== 2. 测试函数（检测标准） ==========
print("🧪 测试正常除法：")
print(f"divide(10, 2) 返回: {divide(10, 2)}")   # 预期输出 5.0

print("\n🧪 测试除零错误（检测重点）：")
print(f"divide(1, 0) 返回: {divide(1, 0)}")     # 预期输出 "除数不能为0"

print("\n🧪 测试其他正常情况：")
print(f"divide(9, 3) 返回: {divide(9, 3)}")     # 预期输出 3.0

# ========== 3. 断言检测（静默通过算过关） ==========
# 检测正常情况
assert divide(10, 2) == 5.0, "❌ 10/2 应该等于 5.0"
assert divide(9, 3) == 3.0, "❌ 9/3 应该等于 3.0"

# 检测异常情况（重点：函数返回了字符串，不是报错崩溃）
assert divide(1, 0) == "除数不能为0", "❌ 除零时应该返回友好提示！"

print("\n✅ 所有检测通过！D4 任务完成！程序未崩溃，除零错误被优雅捕获。")